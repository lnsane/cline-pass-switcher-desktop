// 运行时拼接文本的翻译模式
//
// 界面上很多文本是拼出来的：「渠道 (4)」「还有 338 个未显示」「3 天 11 小时后重置」
// 「26 天 11 小时后重置」。精确表里不会有这些，所以用正则匹配。
//
// 顺序有讲究：**更具体的模式放前面**。「3 天 11 小时后重置」如果不先匹配，
// 会被更宽松的规则截胡。
(function () {
  'use strict';

  window.LOCALE_PATTERNS = window.LOCALE_PATTERNS || {};
  window.LOCALE_PATTERNS.en = [
    // ---------- 倒计时（最具体，放最前）----------
    // "3 天 11 小时后重置" / "2 天 3 小时后重置"
    { re: /^(\d+)\s*天\s*(\d+)\s*小时后重置$/, to: 'Resets in $1d $2h' },
    // "11 小时后重置" / "11 小时 30 分后重置"
    { re: /^(\d+)\s*小时\s*(\d+)\s*分后重置$/, to: 'Resets in $1h $2m' },
    { re: /^(\d+)\s*小时后重置$/, to: 'Resets in $1h' },
    { re: /^(\d+)\s*分钟后重置$/, to: 'Resets in $1m' },
    { re: /^分后重置$/, to: 'Resets in minutes' },
    { re: /^分钟后重置$/, to: 'Resets in minutes' },

    // ---------- 相对时间 ----------
    { re: /^(\d+)\s*秒前$/, to: '$1s ago' },
    { re: /^(\d+)\s*分钟前$/, to: '$1m ago' },
    { re: /^(\d+)\s*小时前$/, to: '$1h ago' },
    { re: /^(\d+)\s*天前$/, to: '$1d ago' },
    { re: /^从未$/, to: 'Never' },

    // ---------- 计数 ----------
    // "渠道 (4)" / "渠道 (31)"
    { re: /^渠道\s*\((\d+)\)$/, to: 'Upstreams ($1)' },
    // "还有 338 个未显示"
    { re: /^还有\s*(\d+)\s*个未显示$/, to: '$1 more not shown' },
    // "10 个已探测管道"
    { re: /^(\d+)\s*个已探测管道$/, to: '$1 probed pipelines' },
    // "1 个已启用"
    { re: /^(\d+)\s*个已启用$/, to: '$1 enabled' },
    // "15 个已启用" 之类
    { re: /^(\d+)\s*个已启用账号$/, to: '$1 enabled accounts' },
    // "0 成功 / 0 失败"
    { re: /^(\d+)\s*成功\s*\/\s*(\d+)\s*失败$/, to: '$1 succeeded / $2 failed' },
    // "100% 成功率" / "% 成功率"
    { re: /^(\d+)%\s*成功率$/, to: '$1% success rate' },
    // "98.5% 命中率"
    { re: /^([\d.]+)%\s*命中率$/, to: '$1% hit rate' },
    // "0 原始输入" / "2,725,243 原始输入"
    { re: /^([\d,]+)\s*原始输入$/, to: '$1 raw input' },
    { re: /^([\d,]+)\s*原始输出$/, to: '$1 raw output' },
    // "0 缓存读取"
    { re: /^([\d,]+)\s*缓存读取$/, to: '$1 cache read' },
    // "26 天 11 小时后重置" 已在上面
    // "0 次样本" / "12 次样本"
    { re: /^([\d,]+)\s*次样本$/, to: '$1 samples' },
    { re: /^([\d,]+)\s*个样本$/, to: '$1 samples' },
    // "最近 0 条（引擎保留 0 条）"
    { re: /^最近\s*([\d,]+)\s*条（引擎保留\s*([\d,]+)\s*条）$/, to: 'Latest $1 (engine keeps $2)' },
    { re: /^最多保留最近\s*(\d+)\s*条$/, to: 'Keeps the latest $1' },
    // "近 14 天"
    { re: /^近\s*(\d+)\s*天$/, to: 'Last $1 days' },
    { re: /^(\d+)\s*天$/, to: '$1 days' },
    // "N 个账号"
    { re: /^([\d,]+)\s*个账号$/, to: '$1 accounts' },
    // "N 个模型"
    { re: /^([\d,]+)\s*个模型$/, to: '$1 models' },
    // "N 个渠道"
    { re: /^([\d,]+)\s*个渠道$/, to: '$1 upstreams' },
    // "N 个文件、"
    { re: /^([\d,]+)\s*个文件、$/, to: '$1 files, ' },
    // "N 个模型、合计约"
    { re: /^([\d,]+)\s*个模型、合计约$/, to: '$1 models, roughly' },
    // "N 个订阅模型，新增"
    { re: /^([\d,]+)\s*个订阅模型，新增$/, to: '$1 subscription models,' },
    // "N 个环境变量"
    { re: /^([\d,]+)\s*个环境变量$/, to: '$1 environment variables' },
    { re: /^([\d,]+)\s*个环境变量：$/, to: '$1 environment variables:' },
    // "N 个顶层键"
    { re: /^([\d,]+)\s*个顶层键$/, to: '$1 top-level keys' },
    // "N 份备份"
    { re: /^([\d,]+)\s*份备份$/, to: '$1 backups' },

    // ---------- 带数字的说明句 ----------
    // "运行中 · 127.0.0.1:3466"
    { re: /^运行中\s*·\s*(.+)$/, to: 'Running · $1' },
    // "代理地址 http://127.0.0.1:3466/v1"
    { re: /^代理地址\s+(https?:\/\/\S+)$/, to: 'Proxy address $1' },
    // "近 14 天 1,151 次请求 · 累计 ... token · $9.98"
    {
      re: /^近\s*(\d+)\s*天\s*([\d,]+)\s*次请求\s*·\s*累计\s*([\d,]+)\s*token\s*·\s*(.+)$/,
      to: 'Last $1 days · $2 requests · $3 tokens · $4',
    },
    // "近 14 天 1,151 次请求 · ...（数据自 2026-09-21 起）"
    {
      re: /^(.+)（数据自\s*(\S+)\s*起）$/,
      to: '$1 (data since $2)',
    },
    // 注意：Claude 配置弹窗的汇总句现在由 claudeconfig.js 用 T() 整句翻译，
    // 不再走这里 —— 被 <b>/<span> 切开的片段正则匹配不到，留着是死代码。
    // "（已存在，12 个环境变量，有 2 份备份）"
    {
      re: /^（已存在，\s*([\d,]+)\s*个环境变量(.*)$/,
      to: '(exists, $1 environment variables$2',
    },
    // "真实 $0.00381 + 估算 $9.98"
    {
      re: /^真实\s*(\S+)\s*\+\s*估算\s*(\S+)$/,
      to: 'Real $1 + estimated $2',
    },
    // "全部为定价表估算" / "全部来自上游真实账单" 走精确表
    // "占比 N%"（分布表里可能有）
    { re: /^(\d+(?:\.\d+)?)%$/, to: '$1%' },
    // "成功 N" / "失败 N"（KPI 副标题）
    { re: /^([\d,]+)\s*成功$/, to: '$1 succeeded' },
    { re: /^([\d,]+)\s*失败$/, to: '$1 failed' },
    // "N 成功 / N 失败"
    { re: /^([\d,]+)\s*成功\s*\/\s*([\d,]+)\s*失败$/, to: '$1 succeeded / $2 failed' },
    // "已用 N%"
    { re: /^(.+)已用\s*([\d.]+)%$/, to: '$1 used $2%' },
    // "第 N 页"之类
    { re: /^第\s*(\d+)\s*页$/, to: 'Page $1' },
    // 时间戳 "09-26" 不动（纯数字）
    // "N 分钟前" 已在上面
    // "N 小时前" 已在上面
  ];
})();
